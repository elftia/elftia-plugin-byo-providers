/**
 * harvest-media-i18n.mjs — import the MEDIA i18n subtree from an explicitly
 * supplied, caller-owned locale export into a static plugin seed module
 * (`src/renderer/host/vendored/mediaI18nSeed.ts`).
 *
 * The relocated media UI (5 panels + components + the shared `ProviderDetailsPanel`)
 * reads keys under these top-level roots (harvested across all media files):
 *   - the FULL `mediaSettings` subtree (from `providers/media.json`) — every
 *     panel's strings (`mediaSettings.{common,image,video,music,asr,tts}.*`), AND
 *   - `settings.status.{saving,saved,error}` (from `settings/core.json`, whose
 *     content already nests under `settings`) — the credential save-status line.
 *
 * NOT harvested here (already in the LLM seed, MERGED into the SAME
 * `byo-providers` namespace at activate): `providerSettings.modelsManager.*`
 * (the model-manager strings) + `common.{cancel,delete,…}`. The media seed's
 * roots (`mediaSettings` + the `settings.status` slice) are DISJOINT from the LLM
 * seed's roots (`providerSettings`/`apiMode`/`presetName`/`common`), so the
 * object spread `{ ...llmSeed, ...mediaSeed }` is collision-free EXCEPT the
 * shared `settings` namespace — but the LLM seed carries NO `settings` root, so
 * there is no `settings.status` collision either.
 *
 * Re-run with a standalone locale export:
 *   node scripts/harvest-media-i18n.mjs --locales-dir <locale-export-directory>
 *
 * @module byo-providers/scripts/harvest-media-i18n
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { resolveLocaleSourceDir } from './lib/locale-source.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const localesDir = resolveLocaleSourceDir(process.argv.slice(2), {
  command: 'node scripts/harvest-media-i18n.mjs',
});

const LANGS = ['en', 'zh', 'ja'];

/** Read and parse one caller-owned locale-export JSON file (UTF-8). */
function readJson(lang, rel) {
  const p = resolve(localesDir, lang, rel);
  return JSON.parse(readFileSync(p, 'utf8'));
}

/** Keep only the listed dotted paths from an object (deep prune). */
function pick(obj, paths) {
  const out = {};
  for (const path of paths) {
    const parts = path.split('.');
    let src = obj;
    let dst = out;
    let ok = true;
    for (let i = 0; i < parts.length; i += 1) {
      const k = parts[i];
      if (src == null || typeof src !== 'object' || !(k in src)) {
        ok = false;
        break;
      }
      if (i === parts.length - 1) {
        dst[k] = src[k];
      } else {
        dst[k] = dst[k] ?? {};
        dst = dst[k];
        src = src[k];
      }
    }
    if (!ok) {
      // eslint-disable-next-line no-console
      console.warn(`[harvest-media-i18n] ${path} missing in this locale — skipped`);
    }
  }
  return out;
}

// `settings/core.json` content already nests under `settings`, so the full keys
// the panels look up are `settings.status.{saving,saved,error}`.
const SETTINGS_KEYS = [
  'settings.status.saving',
  'settings.status.saved',
  'settings.status.error',
];

const resources = {};
for (const lang of LANGS) {
  const media = readJson(lang, 'providers/media.json'); // mediaSettings.* (+ unused imageMode/etc roots)
  const settings = pick(readJson(lang, 'settings/core.json'), SETTINGS_KEYS);
  // Keep ONLY the `mediaSettings` root from media.json (drop imageMode/mediaPanel/
  // musicMode — those are chat-input strings the panels never read).
  resources[lang] = { mediaSettings: media.mediaSettings, ...settings };
}

const banner = `/**
 * mediaI18nSeed.ts — GENERATED by scripts/harvest-media-i18n.mjs. DO NOT EDIT BY HAND.
 *
 * The MEDIA i18n subtree imported from a caller-supplied standalone locale
 * export (the FULL \`mediaSettings\` from \`providers/media.json\` +
 * \`settings.status.{saving,saved,error}\` from \`settings/core.json\`) for en/zh/ja.
 * MERGED into the existing \`byo-providers\` i18n namespace alongside the LLM seed
 * (\`{ ...llmSeed, ...mediaSeed }\`); the roots are disjoint (\`mediaSettings\` +
 * the \`settings\` slice vs the LLM seed's \`providerSettings\`/\`apiMode\`/\`presetName\`/
 * \`common\`). The vendored \`useTranslation\` resolves keys from the merged bundle
 * (key-fallback on miss).
 *
 * @module byo-providers/renderer/host/vendored/mediaI18nSeed
 */
export const mediaI18nSeed: Record<string, Record<string, unknown>> = `;

const out = `${banner}${JSON.stringify(resources, null, 2)};\n`;
const dest = resolve(here, '..', 'src/renderer/host/vendored/mediaI18nSeed.ts');
writeFileSync(dest, out, 'utf8');
// eslint-disable-next-line no-console
console.log(`[harvest-media-i18n] wrote ${dest} (${LANGS.join('/')})`);
